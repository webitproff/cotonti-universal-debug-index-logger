 *  вставляем в корневой файл сайта index.php между строками const COT_CODE = true; и require_once './datas/config.php';
 */
 
 
/* ============================================================================
 * УНИВЕРСАЛЬНАЯ ОТЛАДКА COTONTI → LOG
 * ----------------------------------------------------------------------------
 * Назначение:
 *   Перехватывает Deprecated-предупреждения PHP, приходящие из
 *   system/cotemplate.php (в частности ошибку вида:
 *     Deprecated: str_replace(): Passing null to parameter #3 ($subject)
 *     of type array|string is deprecated in .../system/cotemplate.php:1923
 *   ), собирает максимум контекста и пишет всё в лог-файл.
 *
 * Куда класть:
 *   index.php, сразу после строки:
 *       const COT_CODE = true;
 *   до строки:
 *       require_once './datas/config.php';
 *
 * Куда пишет:
 *   Файл cot_index_debug.log в той же директории, где лежит index.php.
 *   Открывается в режиме дописывания (FILE_APPEND) — при каждом срабатывании
 *   добавляется новый блок, старые не теряются.
 *
 * Управление (три переменные в самом верху блока):
 *   1) $COT_INDEX_DEBUG
 *        true  — отладка активна;
 *        false — блок полностью отключён, обработчик не регистрируется,
 *                ничего никуда не пишется. Ничего резать/вставлять не нужно.
 *
 *   2) $COT_DEBUG_MODE — режим отбора ошибок по файлу.
 *        'all'  — ловить Deprecated из ЛЮБОГО файла (и ядро, и плагины,
 *                 и модули, и темы). Полезно для полного аудита.
 *        'list' — ловить только из файлов, перечисленных в
 *                 $COT_DEBUG_TARGET_FILES.
 *
 *   3) $COT_DEBUG_TARGET_FILES — массив имён файлов для режима 'list'.
 *        Сравнение идёт по ЧАСТИЧНОМУ совпадению пути — достаточно
 *        указать имя файла без пути. Например 'cotemplate.php' поймает
 *        и /home/user/system/cotemplate.php, и любой другой путь,
 *        где встречается эта строка.
 *        В режиме 'all' этот массив игнорируется.
 *
 * Фильтры внутри обработчика (по порядку проверки):
 *   - Фильтр №0 (обязательный) — error_reporting(). Если текущий уровень
 *     отчётности PHP не включает данный тип ошибок, обработчик молча
 *     выходит. Убирать не нужно, это защита от потока лишних записей.
 *   - Фильтр №1 — по тексту сообщения (str_replace). Отсекает всё,
 *     что нас не интересует. Убирается/настраивается отдельно,
 *     если нужно ловить не только Deprecated от str_replace().
 *   - Фильтр №2 — по имени файла. Работает ТОЛЬКО в режиме 'list'.
 *     В режиме 'all' этот фильтр не применяется.
 *
 * Что пишется в лог при срабатывании:
 *   - дата и время;
 *   - ERRNO, текст сообщения об ошибке;
 *   - файл ядра и строка, где ошибка возникла;
 *   - URL, HTTP-метод, Referer, IP, User-Agent;
 *   - имя тега шаблона, вернувшего null (например {PHP.c});
 *   - файл шаблона, в котором тег встретился;
 *   - файл:строка кода-виновника, откуда пришёл вызов парсинга;
 *   - имя плагина/модуля, из которого пришёл вызов;
 *   - полный BACKTRACE (до 60 фреймов) с классами и методами;
 *   - снимок контекста: COT_CODE, env.type, env.ext, env.location, usr.id;
 *   - полные массивы $_GET и $_POST.
 *
 * Важно:
 *   - Файл cot_index_debug.log должен быть доступен на запись
 *     пользователю веб-сервера (обычно www-data). Если не создаётся —
 *     выдать права на директорию.
 *   - Блок можно удалить целиком — движок не затронут, работает только
 *     на уровне index.php.
 *
 * Автор:    — (универсальный шаблон для Cotonti)
 * Версия:   1.1
 * ============================================================================
 */

// ===== УНИВЕРСАЛЬНАЯ ОТЛАДКА COTONTI → LOG =====

// Мастер-выключатель. true = отладка включена, false = полностью выключена.
$COT_INDEX_DEBUG = true;

// Режим отбора ошибок по файлу:
//   'all'  — ловить из любого файла;
//   'list' — ловить только из файлов, перечисленных ниже.
$COT_DEBUG_MODE = 'all';

// Список файлов для режима 'list'. Сравнение — по частичному совпадению
// пути, поэтому достаточно указать имя файла без директории.
// В режиме 'all' этот массив не используется.
$COT_DEBUG_TARGET_FILES = [
    'cotemplate.php',   // шаблонизатор Cotonti
    // 'functions.php', // ядро (пример: раскомментировать при необходимости)
    // 'common.php',    // ядро
    // 'extrafields.php',// API доп. полей
    // 'forms.php',     // API форм
];

if ($COT_INDEX_DEBUG) {

    // Регистрируем собственный обработчик ошибок PHP.
    // Возврат false в колбэке = «не подавлять», ошибка уходит дальше
    // по стандартной цепочке PHP (Deprecated всё равно попадёт в логи php).
    set_error_handler(function ($errno, $errstr, $errfile, $errline)
        use ($COT_DEBUG_MODE, $COT_DEBUG_TARGET_FILES) {

        // ------------------------------------------------------------------
        // ФИЛЬТР №0 (обязательный) — уровень error_reporting().
        // Если текущий уровень отчётности PHP не включает данный тип ошибок,
        // обработчик молча выходит. Это защита от потока лишних записей.
        // ------------------------------------------------------------------
        if (!(error_reporting() & $errno)) return false;

        // ------------------------------------------------------------------
        // ФИЛЬТР №1 — по тексту сообщения.
        // Отсекает всё, что не относится к str_replace().
        // Если нужен полный лог без фильтрации по тексту — закомментировать
        // или удалить эту строку.
        // ------------------------------------------------------------------
        if (strpos($errstr, 'str_replace') === false) return false;

        // ------------------------------------------------------------------
        // ФИЛЬТР №2 — по имени файла. Работает ТОЛЬКО в режиме 'list'.
        // В режиме 'all' этот блок пропускается и ловятся ошибки из всех файлов.
        // ------------------------------------------------------------------
        if ($COT_DEBUG_MODE === 'list') {
            $cot_match = false;
            foreach ($COT_DEBUG_TARGET_FILES as $cot_f) {
                if (strpos($errfile, $cot_f) !== false) {
                    $cot_match = true;
                    break;
                }
            }
            if (!$cot_match) return false;
        }

        // Полный бэктрейс со всеми объектами и аргументами функций.
        // 60 фреймов — с запасом хватает на цепочку «index.php → plugin → module → template».
        // Без IGNORE_ARGS — именно аргументы позволяют вытащить имя тега.
        $bt = debug_backtrace(DEBUG_BACKTRACE_PROVIDE_OBJECT, 60);

        // Инициализация полей, которые заполняются по ходу обхода бэктрейса.
        $tag     = '?';   // имя тега шаблона, вернувшего null
        $tpl     = '?';   // файл шаблона
        $caller  = '?';   // файл:строка, откуда пришёл вызов парсинга
        $suspect = 'core';// модуль или плагин-виновник

        // Обходим все фреймы бэктрейса сверху вниз.
        foreach ($bt as $f) {

            // --- Извлекаем имя тега и файл шаблона из аргументов функций ---
            // preg_replace_callback внутри cotemplate.php передаёт замыканию
            // массив $matches, где есть ключ 'tag' — это и есть имя тега.
            // А $params['tpl'] содержит объект XTemplate с полем filename.
            if (!empty($f['args']) && is_array($f['args'])) {
                foreach ($f['args'] as $a) {
                    // Массив с ключом 'tag' → имя тега.
                    if (is_array($a) && isset($a['tag']) && is_string($a['tag'])) {
                        $tag = $a['tag'];
                    }
                    // Объект с полем filename → файл шаблона.
                    if (is_object($a) && isset($a->filename)) {
                        $tpl = $a->filename;
                    }
                }
            }

            // --- Определяем первого виновника вне движка ---
            // Идём от точки ошибки наружу. Первый файл, не cotemplate.php,
            // это и есть тот код, который дёрнул парсинг (модуль/плагин).
            if ($caller === '?' && !empty($f['file']) && strpos($f['file'], 'cotemplate.php') === false) {
                $caller = $f['file'] . ':' . ($f['line'] ?? '?');
            }

            // --- Определяем имя плагина/модуля по пути ---
            // Ищем в пути сегмент /plugins/<name>/ или /modules/<name>/.
            // Берём первое найденное — это ближайший внешний виновник.
            if ($suspect === 'core' && !empty($f['file']) && preg_match('#/(plugins|modules)/([^/]+)/#', $f['file'], $m)) {
                $suspect = $m[1] . '/' . $m[2];
            }
        }


        // ------------------------------------------------------------------
        // Формируем лог. Строки собираются конкатенацией в одну переменную,
        // чтобы записать файл одним вызовом file_put_contents с LOCK_EX —
        // это защищает от порчи лога при параллельных запросах.
        // ------------------------------------------------------------------

        // Пустая строка-разделитель перед новым блоком (визуально отделяет
        // записи друг от друга в файле).
        $log  = "\n";

        // Верхняя разделительная линия из 56 символов "=".
        $log .= "========================================================\n";

        // Дата и время срабатывания отладки в формате YYYY-MM-DD HH:MM:SS.
        $log .= "DATE:       " . date('Y-m-d H:i:s') . "\n";

        // Числовой код ошибки PHP. Для Deprecated это 8192 (E_DEPRECATED).
        $log .= "ERRNO:      {$errno}\n";

        // Полный текст сообщения об ошибке — то самое "str_replace(): Passing null...".
        $log .= "MESSAGE:    {$errstr}\n";

        // Файл ядра и строка, где PHP зафиксировал ошибку (cotemplate.php:1923).
        $log .= "CORE FILE:  {$errfile}:{$errline}\n";

        // Полный URI запроса, на котором сработала ошибка (путь + query-строка).
        $log .= "URL:        " . ($_SERVER['REQUEST_URI'] ?? '') . "\n";

        // HTTP-метод запроса: GET, POST и т.д.
        $log .= "METHOD:     " . ($_SERVER['REQUEST_METHOD'] ?? '') . "\n";

        // Откуда пришёл пользователь. Прочерк, если заголовок не передан.
        $log .= "REFERER:    " . ($_SERVER['HTTP_REFERER'] ?? '-') . "\n";

        // IP-адрес клиента, с которого сделан запрос.
        $log .= "IP:         " . ($_SERVER['REMOTE_ADDR'] ?? '-') . "\n";

        // Строка User-Agent браузера целиком.
        $log .= "USER-AGENT: " . ($_SERVER['HTTP_USER_AGENT'] ?? '-') . "\n";

        // Разделительная линия из 56 символов "-" между блоком запроса и блоком парсинга.
        $log .= "--------------------------------------------------------\n";

        // Текущий режим отладки — удобно видеть в логе, в каком режиме сработало.
        $log .= "DEBUG MODE: {$COT_DEBUG_MODE}\n";

        // Имя тега шаблона, вернувшего null (например {PHP.c}). В фигурных скобках,
        // чтобы при чтении лога сразу было видно: это именно тег, а не просто текст.
        $log .= "ТЕГ:        {" . $tag . "}\n";

        // Файл шаблона, в котором встретился проблемный тег (например market.tpl).
        $log .= "ШАБЛОН:     {$tpl}\n";

        // Файл:строка кода, который дёрнул парсинг и привёл к null.
        // Обычно это PHP-файл модуля/плагина — например market.preview.php:244.
        $log .= "ВИНОВНИК:   {$caller}\n";

        // Имя плагина или модуля, из которого пришёл вызов.
        // Определяется по сегменту пути /plugins/<name>/ или /modules/<name>/.
        // Если ошибка возникла вне плагина/модуля — пишется "core".
        $log .= "ПЛАГИН:     {$suspect}\n";

        // Нижняя разделительная линия перед блоком BACKTRACE.
        $log .= "--------------------------------------------------------\n";

        // BACKTRACE — вся цепочка вызовов от точки ошибки к точке входа.
        $log .= "=== BACKTRACE ===\n";
        foreach ($bt as $i => $f) {
            if (empty($f['file'])) {
                // Внутренние вызовы PHP (без файла).
                $log .= "#{$i} [internal]\n";
                continue;
            }
            $log .= "#{$i} {$f['file']}:{$f['line']}";
            if (!empty($f['function'])) {
                // Для методов добавляем имя класса через ::.
                $log .= " → " . (!empty($f['class']) ? $f['class'] . '::' : '') . $f['function'] . "()";
            }
            $log .= "\n";
        }
        $log .= "=== /BACKTRACE ===\n";

        // CONTEXT — снимок окружения на момент ошибки.
        $log .= "\n--- CONTEXT ---\n";
        if (defined('COT_CODE'))      $log .= "COT_CODE:  defined\n";
        if (class_exists('Cot')) {
            if (isset(Cot::$env['type']))     $log .= "env.type:  " . Cot::$env['type'] . "\n";
            if (isset(Cot::$env['ext']))      $log .= "env.ext:   " . Cot::$env['ext'] . "\n";
            if (isset(Cot::$env['location'])) $log .= "env.loc:   " . Cot::$env['location'] . "\n";
            if (isset(Cot::$usr['id']))       $log .= "usr.id:    " . Cot::$usr['id'] . "\n";
        }

        // GET и POST в JSON — удобно читать и парсить.
        $log .= "GET:  " . json_encode($_GET, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n";
        $log .= "POST: " . json_encode($_POST, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) . "\n";
        $log .= "========================================================\n";

        // Пишем в файл рядом с index.php.
        // __DIR__ — директория текущего файла (index.php).
        // FILE_APPEND — дописывать в конец, не перезаписывать.
        // LOCK_EX — эксклюзивная блокировка файла на время записи.
        file_put_contents(__DIR__ . '/cot_index_debug.log', $log, FILE_APPEND | LOCK_EX);

        // false = не подавляем ошибку, PHP продолжает свою обработку.
        return false;
    });
}

// ===== /УНИВЕРСАЛЬНАЯ ОТЛАДКА =====



